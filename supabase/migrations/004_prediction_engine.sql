-- ===== Behavioral Predictions Table =====
-- Tracks predictions of user behavior based on historical patterns
-- Examples: abandonment risk after scope creep, motivation spike after shipping

CREATE TABLE IF NOT EXISTS behavioral_predictions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  prediction_type TEXT NOT NULL CHECK (prediction_type IN ('abandonment_risk', 'burnout_risk', 'momentum_collapse', 'avoidance_loop', 'motivation_spike', 'execution_drift')),
  trigger_condition TEXT NOT NULL,
  predicted_behavior TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'validated', 'invalidated')),
  confidence FLOAT NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
  related_pattern_id UUID REFERENCES execution_patterns(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_behavioral_predictions_user ON behavioral_predictions(user_id);
CREATE INDEX idx_behavioral_predictions_status ON behavioral_predictions(user_id, status);

COMMENT ON TABLE behavioral_predictions IS 'Predictions of user behavior generated by the Prediction Engine';
COMMENT ON COLUMN behavioral_predictions.trigger_condition IS 'What triggers this prediction (e.g., "User added 3 new goals while 5 tasks are overdue")';
COMMENT ON COLUMN behavioral_predictions.predicted_behavior IS 'What the AI expects to happen (e.g., "User will abandon the current project within 48 hours")';
COMMENT ON COLUMN behavioral_predictions.status IS 'active: currently monitoring, validated: prediction came true, invalidated: prediction was wrong/averted';

-- ===== Behavioral Reports Table =====
-- Stores weekly intelligence reports summarizing execution history

CREATE TABLE IF NOT EXISTS behavioral_reports (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  report_date DATE NOT NULL DEFAULT CURRENT_DATE,
  period_start TIMESTAMPTZ NOT NULL,
  period_end TIMESTAMPTZ NOT NULL,
  report_content JSONB NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_behavioral_reports_user ON behavioral_reports(user_id);
CREATE INDEX idx_behavioral_reports_date ON behavioral_reports(user_id, report_date DESC);

COMMENT ON TABLE behavioral_reports IS 'Weekly behavioral intelligence reports containing execution insights, momentum shifts, and validated predictions';

-- ===== RLS Policies =====

-- Behavioral Predictions RLS
ALTER TABLE behavioral_predictions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own predictions"
  ON behavioral_predictions FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "Service role can insert predictions"
  ON behavioral_predictions FOR INSERT
  WITH CHECK (true);

CREATE POLICY "Service role can update predictions"
  ON behavioral_predictions FOR UPDATE
  USING (true);

-- Behavioral Reports RLS
ALTER TABLE behavioral_reports ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own reports"
  ON behavioral_reports FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "Service role can insert reports"
  ON behavioral_reports FOR INSERT
  WITH CHECK (true);

-- ===== Helper Functions =====

-- Function to get active predictions for a user
CREATE OR REPLACE FUNCTION get_active_predictions(p_user_id UUID)
RETURNS JSON AS $$
DECLARE
  result JSON;
BEGIN
  SELECT json_agg(json_build_object(
    'id', id,
    'prediction_type', prediction_type,
    'trigger_condition', trigger_condition,
    'predicted_behavior', predicted_behavior,
    'confidence', confidence,
    'created_at', created_at
  ))
  FROM behavioral_predictions
  WHERE user_id = p_user_id
    AND status = 'active'
  ORDER BY confidence DESC, created_at DESC
  INTO result;
  
  RETURN COALESCE(result, '[]'::json);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

